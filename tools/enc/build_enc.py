#!/usr/bin/env python3
"""Вставляет в docs/chess/zoo-chess.html новые семейства (new_families.py) и данные энциклопедии (enc_ru.py).

Код заменяется между метками // <<NEW_FAMILIES>> … // <</NEW_FAMILIES>> и // <<ENC>> … // <</ENC>>,
поэтому скрипт можно запускать повторно.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import enc_ru  # noqa: E402
import new_families  # noqa: E402

GAME = os.path.join(HERE, '..', '..', 'docs', 'chess', 'zoo-chess.html')
J = lambda x: json.dumps(x, ensure_ascii=False)  # noqa: E731


def fam_js():
    out = ['  // <<NEW_FAMILIES>> (generated by tools/enc/build_enc.py)']
    facts = []
    for fid, F in new_families.FAMS.items():
        parts = [f"name: {J(F['name'])}, gen: {J(F['gen'])}, kingdom: {J(F['kname'])}, ground: {J(F['ground'])}, crest: {J(F['crest'])}",
                 f"die: {J(F['die'])}, land: {J(F['land'])}, mated: {J(F['mated'])}"]
        fk = {}
        for r in 'kqrbnp':
            a, n, mv, why, fact = F['p'][r][:5]
            extra = ', per: 230, base: 170, tilt: 3' if mv == 'walk' else ''
            say = ''
            out_p = f"{r}: {{ a: {J(a)}, n: {J(n)}, mv: {J(mv)}{extra}, why: {J(why)}{say} }}"
            parts.append(out_p)
            fk[r] = fact
        out.append(f"  fam({J(fid)}, {{\n    " + ',\n    '.join(parts) + ',\n  });')
        facts.append(f"  FACTS[{J(fid)}] = {J(fk)};")
    out.append('  // <</NEW_FAMILIES>>')
    return '\n'.join(out), '  // <<NEW_FACTS>>\n' + '\n'.join(facts) + '\n  // <</NEW_FACTS>>'


def enc_js():
    p = {}
    for fid, roles in enc_ru.P.items():
        for r, v in roles.items():
            p[f'{fid}-{r}'] = list(v)
    fdesc = dict(enc_ru.FAMILIES)
    for fid, F in new_families.FAMS.items():
        fdesc[fid] = F['desc']
        for r in 'kqrbnp':
            v = F['p'][r]
            p[f'{fid}-{r}'] = [v[5], v[6], v[7], v[8]]
    data = {'k': enc_ru.KINGDOMS, 'f': fdesc, 'p': p}
    return '  // <<ENC>> (generated by tools/enc/build_enc.py)\n  const ENC = ' + J(data) + ';\n  // <</ENC>>'


def put(html, tag, block, anchor):
    pat = re.compile(r'  // <<' + tag + r'>>.*?// <</' + tag + r'>>', re.S)
    if pat.search(html):
        return pat.sub(lambda m: block, html)
    i = html.index(anchor)
    return html[:i] + block + '\n' + html[i:]


def main():
    html = open(GAME, encoding='utf-8').read()
    # families must exist before KINGDOM_LIST is built
    fams, facts = fam_js()
    html = put(html, 'NEW_FAMILIES', fams, "  ARMIES.savanna.kingdom = ")
    html = put(html, 'NEW_FACTS', facts, "  Object.entries(FACTS).forEach(")
    html = put(html, 'ENC', enc_js(), "  const paintLineup = ")
    # kingdom lists, army order and prices
    adds = {'plants': ['cereals', 'carnivorous', 'succulents'], 'fungi': ['poisonfungi', 'farmfungi', 'treefungi'],
            'bacteria': ['cyano', 'spiro', 'actino'], 'viruses': ['giantvir', 'plantvir', 'archvir']}
    base = {'plants': "'flowers', 'trees'", 'fungi': "'capfungi', 'oddfungi'", 'bacteria': "'cocci', 'rods'", 'viruses': "'phages', 'virions'"}
    for k, extra in adds.items():
        new = base[k] + ''.join(f", '{x}'" for x in extra)
        html = re.sub(r"(\{ id: '" + k + r"', n: '[^']+', e: '[^']+', fams: \[)[^\]]*(\])", lambda m: m.group(1) + new + m.group(2), html)
    ids = "['classic', 'savanna', 'ocean', 'cats', 'primates', 'birds', 'whales', 'sharks', 'flowers', 'trees', 'cereals', 'carnivorous', 'succulents', " \
          "'capfungi', 'oddfungi', 'poisonfungi', 'farmfungi', 'treefungi', 'cocci', 'rods', 'cyano', 'spiro', 'actino', 'phages', 'virions', " \
          "'giantvir', 'plantvir', 'archvir', 'stone', 'iron', 'industrial', 'human', 'tech']"
    html = re.sub(r"const ARMY_IDS = \[[^\]]*\];", 'const ARMY_IDS = ' + ids + ';', html)
    open(GAME, 'w', encoding='utf-8').write(html)
    print('families', len(new_families.FAMS), 'encyclopedia pieces', len(json.loads(enc_js().split('const ENC = ')[1].split(';\n')[0])['p']))


if __name__ == '__main__' and len(sys.argv) == 1:
    main()


def translations():
    """ru → (en, uz) pairs for every encyclopedia text; chips are matched one by one."""
    import enc_en
    import enc_uz
    pairs, warn = {}, []

    def add(ru, en, uz):
        if ru and en and uz:
            pairs[ru] = (en, uz)

    def chips(ru, en, uz, where):
        a, b, c = ru.split('|'), en.split('|'), uz.split('|')
        if len(a) == len(b) == len(c):
            for x, y, z in zip(a, b, c):
                add(x, y, z)
        else:
            warn.append(where)

    for k in enc_ru.KINGDOMS:
        add(enc_ru.KINGDOMS[k], enc_en.KINGDOMS[k], enc_uz.KINGDOMS[k])
    for f in enc_ru.FAMILIES:
        add(enc_ru.FAMILIES[f], enc_en.FAMILIES[f], enc_uz.FAMILIES[f])
    for f, roles in enc_ru.P.items():
        for r, v in roles.items():
            e, u = enc_en.P[f][r], enc_uz.P[f][r]
            for i in (0, 2, 3):
                add(v[i], e[i], u[i])
            chips(v[1], e[1], u[1], f + '-' + r)
    for f, F in new_families.FAMS.items():
        add(F['desc'], enc_en.NEW_DESC[f], enc_uz.NEW_DESC[f])
        for r in 'kqrbnp':
            v = F['p'][r]
            e, u = enc_en.NEW[f][r], enc_uz.NEW[f][r]
            # v: (art, name, mv, why, fact, about, chips, f2, f3); e/u: (why, fact, about, chips, f2, f3)
            for vi, ei in ((3, 0), (4, 1), (5, 2), (7, 4), (8, 5)):
                add(v[vi], e[ei], u[ei])
            chips(v[6], e[3], u[3], f + '-' + r)
    return pairs, warn


def merge_i18n():
    html = open(GAME, encoding='utf-8').read()
    m = re.search(r'const I18N = (\{.*?\});\n', html, re.S)
    I = json.loads(m.group(1))
    pairs, warn = translations()
    for ru, (en, uz) in pairs.items():
        I['en'][ru] = en
        I['uz'][ru] = uz
    html = html[:m.start(1)] + json.dumps(I, ensure_ascii=False) + html[m.end(1):]
    open(GAME, 'w', encoding='utf-8').write(html)
    print('translated strings', len(pairs), 'chip mismatches', warn)


if __name__ == '__main__' and len(sys.argv) > 1 and sys.argv[1] == 'i18n':
    merge_i18n()
