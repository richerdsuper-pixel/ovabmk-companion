 ("90-ОП", ["Оққўрғон","Қоқайди","Жарқишлоқ","Яккабоғ"]),
 ("91-ОП", ["Янги ариқ","Тўла","Офтоб макон","Тамаддун"]),
 ("92-ОП", ["Хўшчекка","Лайлакхона","Озод","Эзгулик"]),
 ("93-ОП", ["Бахштепа","Бахштепа-1","Какан","Саксанкапа","Жойилма"]),
